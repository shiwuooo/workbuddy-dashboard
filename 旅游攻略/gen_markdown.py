def dist(a, b):
    R = 6371; r = math.radians
    dlat = r(b[1]-a[1]); dlng = r(b[0]-a[0])
    s = math.sin(dlat/2)**2 + math.cos(r(a[1]))*math.cos(r(b[1]))*math.sin(dlng/2)**2
    return R*2*math.atan2(math.sqrt(s), math.sqrt(1-s))

