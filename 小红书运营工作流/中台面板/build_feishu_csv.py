# -*- coding: utf-8 -*-
"""爆款作战中台 · C 飞书多维表格导入包生成器
从 运营数据库.json 生成 7 张飞书多维表格的导入就绪 CSV + 设计说明.md
用法：python build_feishu_csv.py  → 输出到 飞书多维表格导入包/
"""
import json, os, csv

BASE = "D:/workbuddy/小红书运营工作流"
DB = os.path.join(BASE, "运营数据库.json")
OUT = os.path.join(BASE, "中台面板/飞书多维表格导入包")
os.makedirs(OUT, exist_ok=True)
db = json.load(open(DB, encoding="utf-8"))
cai = db["素材库"]

def w(name, header, rows):
    p = os.path.join(OUT, name)
    with open(p, "w", encoding="utf-8-sig", newline="") as f:
        wtr = csv.writer(f)
        wtr.writerow(header)
        for r in rows:
            wtr.writerow(r)
    print("  ✓", name, f"({len(rows)}行)")

# 1. 素材库总表（扁平化10类）
rows = []
cat_cn = {
    "选题库": "选题库", "标题库": "标题库", "封面模板库": "封面模板库", "钩子金句库": "钩子金句库",
    "评论话术库": "评论话术库", "竞品对标库": "竞品对标库", "爆款档案": "爆款档案",
    "人设声音档案": "人设声音档案", "热点日历": "热点日历", "违规限流案例库": "违规限流案例库",
}
for cat, items in cai.items():
    for it in items:
        content = it.get("内容") or it.get("模板") or it.get("名称") or it.get("金句") or it.get("观察") or it.get("案例") or it.get("事件") or str(it)
        extra = it.get("范例") or it.get("要素") or it.get("人性") or it.get("对照结论") or it.get("教训") or it.get("动作") or it.get("标签") or it.get("来源") or it.get("版本") or it.get("话术") or ""
        if isinstance(extra, list):
            extra = "、".join(map(str, extra))
        rows.append([cat_cn.get(cat, cat), content, str(extra).replace("\n", " "), it.get("日期", ""), it.get("来源", "")])
w("1_素材库总表.csv", ["分类", "内容/标题", "标签/说明", "日期", "来源"], rows)

# 2. 爆款逻辑文档表
docs = [
    ["爆款公式", "我的爆款截图/我的爆款公式 v1.0.md", "结构/钩子/视觉/话术方法论（脱敏版）"],
    ["爆款判断逻辑", "爆款判断逻辑.md", "平台算法+通用骨架+钩子库+视觉+引流引擎"],
    ["爆款底层逻辑", "爆款底层逻辑（人性+小沈+dontbesilent 融合）.md", "人性七定律+7角度对照+11项自检"],
]
w("2_爆款逻辑文档表.csv", ["文档名", "路径", "用途"], docs)

# 3. 生成物变体表
vrows = [[v.get("id"), v.get("模块"), v.get("老师"), v.get("标题"), v.get("人性落点"), v.get("文件")] for v in cai["爆款档案"]]
w("3_生成物变体表.csv", ["ID", "模块", "老师", "标题", "人性落点", "文件"], vrows)

# 4. 发布排期表
srows = [[s.get("日期"), s.get("账号"), s.get("模块"), s.get("变体"), s.get("状态"), s.get("合规闸门")] for s in db["发布排期"]]
w("4_发布排期表.csv", ["日期", "账号", "模块", "变体", "状态", "合规闸门"], srows)

# 5. 复盘记录表
rrows = [[r.get("日期"), r.get("标题"), r.get("结果"), r.get("原因"), r.get("异常信号"), r.get("回写结论")] for r in db["复盘记录"]]
w("5_复盘记录表.csv", ["日期", "标题/主题", "结果", "我的判断原因", "异常信号", "回写结论"], rrows)

# 6. 资产中心表
a = db["资产中心"]
arows = [["人设卡", k, str(v)] for k, v in a["人设卡"].items()]
arows += [["封面模板", t, ""] for t in a["封面模板"]]
arows += [["图片库", t, ""] for t in a["图片库"]]
w("6_资产中心表.csv", ["类型", "名称", "内容"], arows)

# 7. 合规闸门检查表
checks = [
    ["捷径钩子", "代理努力/走捷径自我欺骗许可", "必过"],
    ["低启动成本", "几节/倍速/几分钟，认知吝啬", "必过"],
    ["稀缺紧迫", "损失厌恶+怕错过", "必过"],
    ["群体共识", "别人都在冲/考公人选出来", "必过"],
    ["沉默解除", "替受众认怂/我替你问", "必过"],
    ["立场锁定", "框架理论把学不会归外因", "必过"],
    ["表达降维", "大字报/口语/真实图降认知负荷", "必过"],
    ["权威代理", "老师IP背书把羞耻外包", "必过"],
    ["评论区设计", "A/B版暗号+互动钩子", "必过"],
    ["合规暗号", "無償/群聊且无明写敏感词", "必过"],
    ["产品闭环", "诱饵→群聊→网盘口令链路清晰", "必过"],
]
w("7_合规闸门检查表.csv", ["检查项", "说明", "是否必过"], checks)

# 设计说明
design = """# 飞书多维表格 · 爆书作战中台设计说明

> 本包为「爆款作战中台」在飞书多维表格的落地方案。7 张表已导出为 CSV（UTF-8-BOM，飞书可直接导入）。
> 数据来源与 A(静态HTML)、B(Streamlit) 完全一致：均为 `运营数据库.json` 的同步快照。

## 导入步骤（零 API）
1. 飞书 → 新建「多维表格」
2. 每张表：右上角 `...` → 导入 → 上传对应 CSV
3. 字段类型按下表设置；首行即表头

## 表结构总览
| 表 | 字段 | 关键视图建议 |
|---|---|---|
| 1 素材库总表 | 分类/内容/标签说明/日期/来源 | 按「分类」分组视图；筛选器按标签 |
| 2 爆款逻辑文档表 | 文档名/路径/用途 | 卡片视图（路径可点开本地文件） |
| 3 生成物变体表 | ID/模块/老师/标题/人性落点/文件 | 看板按「模块」；画廊按老师 |
| 4 发布排期表 | 日期/账号/模块/变体/状态/合规闸门 | 日历视图(按日期)；看板按状态 |
| 5 复盘记录表 | 日期/标题/结果/原因/异常信号/回写结论 | 看板按结果；筛选「没爆」 |
| 6 资产中心表 | 类型/名称/内容 | 看板按类型 |
| 7 合规闸门检查表 | 检查项/说明/必过 | 复选框视图 |

## 自动化建议（飞书多维表格「自动化」）
- 当「发布排期表.合规闸门」=通过 且 状态=待发 → 提醒发布
- 当「复盘记录表.结果」=没爆 → 通知复盘并回写爆款逻辑
- 当「素材库总表」新增行 → 同步提示去生成变体

## 与 A/B 的关系
- A/B/C 三套前端共享同一份事实：本机 `运营数据库.json`
- 飞书表适合**手机看 + 多人协作文档记录**；A 适合双击即开的本地全景；B 适合在电脑上真编辑/跑生成
- 后续若要飞书与本地双向同步，需连接 `feishu 飞书` 连接器后由 AI 脚本桥接
"""
open(os.path.join(OUT, "设计说明.md"), "w", encoding="utf-8").write(design)
print("  ✓ 设计说明.md")
print("输出目录:", OUT)
